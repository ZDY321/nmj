import { expect, test, type Page } from "@playwright/test";
import { createBenchmarkVault } from "./fixtures";
import { openSyntheticWorkspace } from "./session";

function listFilter(page: Page, allLabel: string) {
  return page.locator("select").filter({ has: page.locator("option").getByText(allLabel, { exact: true }) });
}
function studentRows(page: Page) {
  return page.getByRole("checkbox", { name: /^选择学生 / });
}

test("student creation preserves sequential confirmations, draft retention and field reset", async ({ page, context }) => {
  const vault = createBenchmarkVault({ students: 12, courses: 1, lessons: 3 });
  vault.profile.homeCampusId = "campus_a";
  vault.students[0] = { ...vault.students[0], grade: undefined, defaultCampusId: "campus_b", status: "paused" };
  const session = await openSyntheticWorkspace(page, context, vault);
  await page.getByRole("button", { name: "档案信息", exact: true }).click();
  await page.getByRole("button", { name: "学生列表", exact: true }).click();
  const form = page.locator('form[data-onboarding="student-form"]');
  const name = form.getByPlaceholder("例如：学生 E");
  const grade = form.locator("select").filter({ has: page.locator("option").getByText("未设置年级", { exact: true }) });
  const campus = form.locator("select").filter({ has: page.locator("option").getByText("未设置校区", { exact: true }) });
  const batch = page.locator("textarea");
  await name.fill("  合成学生0000  ");
  await form.getByPlaceholder("所在学校，例如：实验中学").fill("  新学校  ");
  await form.getByPlaceholder("档案备注，可选").fill("  新备注  ");
  await form.getByRole("checkbox", { name: "临时试听学生", exact: true }).check();
  await campus.selectOption("campus_b");
  await batch.fill("保留批量草稿");
  await page.getByPlaceholder("搜索学生姓名、学校或备注").fill("0001");
  await page.getByRole("button", { name: "添加课程档案", exact: true }).click();
  await page.getByRole("button", { name: "学生列表", exact: true }).click();
  await expect(name).toHaveValue("  合成学生0000  ");
  await expect(batch).toHaveValue("保留批量草稿");
  await expect(page.getByPlaceholder("搜索学生姓名、学校或备注")).toHaveValue("0001");
  const before = session.saveCount;
  const submit = form.getByRole("button", { name: "添加学生", exact: true });
  const missing = page.getByRole("dialog", { name: "未设置学生年级？", exact: true });
  const duplicate = page.getByRole("dialog", { name: "可能重复添加学生", exact: true });
  await submit.click();
  await missing.getByRole("button", { name: "返回设置", exact: true }).click();
  expect(session.saveCount).toBe(before);
  await expect(name).toHaveValue("  合成学生0000  ");
  await submit.click();
  await missing.getByRole("button", { name: "仍然添加", exact: true }).click();
  await expect(duplicate).toContainText("当前已归档");
  await duplicate.getByRole("button", { name: "取消", exact: true }).click();
  expect((await session.readSavedVault()).students).toEqual(vault.students);
  await submit.click();
  await missing.getByRole("button", { name: "仍然添加", exact: true }).click();
  await duplicate.getByRole("button", { name: "仍然添加", exact: true }).click();
  await expect.poll(async () => (await session.readSavedVault()).students.length).toBe(13);
  const saved = await session.readSavedVault();
  const added = saved.students.find(student => !vault.students.some(original => original.id === student.id));
  expect(added).toMatchObject({ name: "合成学生0000", school: "新学校", note: "新备注", defaultCampusId: "campus_b", temporaryTrial: true, status: "active" });
  expect(added?.grade).toBeUndefined();
  expect(saved.students.filter(student => vault.students.some(original => original.id === student.id))).toEqual(vault.students);
  expect(saved.courseGroups).toEqual(vault.courseGroups);
  expect(saved.lessons).toEqual(vault.lessons);
  await expect(name).toHaveValue("");
  await expect(grade).toHaveValue("");
  await expect(form.getByPlaceholder("所在学校，例如：实验中学")).toHaveValue("");
  await expect(form.getByRole("checkbox", { name: "临时试听学生", exact: true })).not.toBeChecked();
  await expect(campus).toHaveValue("campus_b");
  await expect(batch).toHaveValue("保留批量草稿");
  await expect(page.getByPlaceholder("搜索学生姓名、学校或备注")).toHaveValue("0001");
  expect(session.pageErrors).toEqual([]);
  expect(session.unexpectedRequests).toEqual([]);
});

test("student batch import preserves defaults, duplicate skipping and missing-grade cancellation", async ({ page, context }) => {
  const vault = createBenchmarkVault({ students: 12, courses: 1, lessons: 3 });
  vault.profile.homeCampusId = "campus_a";
  const session = await openSyntheticWorkspace(page, context, vault);
  await page.getByRole("button", { name: "档案信息", exact: true }).click();
  await page.getByRole("button", { name: "学生列表", exact: true }).click();
  const form = page.locator('form[data-onboarding="student-form"]');
  const grade = form.locator("select").filter({ has: page.locator("option").getByText("未设置年级", { exact: true }) });
  const campus = form.locator("select").filter({ has: page.locator("option").getByText("未设置校区", { exact: true }) });
  await form.getByPlaceholder("例如：学生 E").fill("保留单人草稿");
  await grade.selectOption("初二");
  await campus.selectOption("campus_b");
  await form.getByPlaceholder("所在学校，例如：实验中学").fill("  默认学校  ");
  await form.getByPlaceholder("档案备注，可选").fill("  默认备注  ");
  await form.getByRole("checkbox", { name: "临时试听学生", exact: true }).check();
  const batch = page.locator("textarea");
  const submit = page.getByRole("button", { name: "批量添加", exact: true });
  await batch.fill("姓名｜年级｜学校｜备注\n合成学生0001｜初三\n新生甲\n新生乙|初一||额外备注|第二段\n新 生 甲|初二");
  await submit.click();
  await expect.poll(async () => (await session.readSavedVault()).students.length).toBe(14);
  await expect(page.getByText("已批量添加 2 名学生，跳过 2 条重复记录。", { exact: true })).toBeVisible();
  let saved = await session.readSavedVault();
  const added = saved.students.filter(student => !vault.students.some(original => original.id === student.id));
  expect(added.map(({ id: _id, ...student }) => student)).toEqual([
    { name: "新生甲", grade: "初二", school: "默认学校", defaultCampusId: "campus_b", note: "默认备注", temporaryTrial: true, status: "active" },
    { name: "新生乙", grade: "初一", school: "默认学校", defaultCampusId: "campus_b", note: "额外备注，第二段", temporaryTrial: true, status: "active" }
  ]);
  await expect(batch).toHaveValue("");
  await expect(form.getByPlaceholder("例如：学生 E")).toHaveValue("保留单人草稿");
  await expect(grade).toHaveValue("初二");
  await expect(form.getByRole("checkbox", { name: "临时试听学生", exact: true })).toBeChecked();
  const beforeDuplicates = session.saveCount;
  await batch.fill("新生甲\n新 生 甲|初二");
  await submit.click();
  await expect(page.getByText("没有新增学生，已跳过 2 条重复记录。", { exact: true })).toBeVisible();
  await expect(batch).toHaveValue("新生甲\n新 生 甲|初二");
  expect(session.saveCount).toBe(beforeDuplicates);
  await grade.selectOption("");
  await batch.fill("无年级新生");
  await submit.click();
  const missing = page.getByRole("dialog", { name: "批量添加包含未设置年级的学生？", exact: true });
  await missing.getByRole("button", { name: "返回设置", exact: true }).click();
  await expect(batch).toHaveValue("无年级新生");
  expect((await session.readSavedVault()).students.length).toBe(14);
  await submit.click();
  await missing.getByRole("button", { name: "仍然添加", exact: true }).click();
  await expect.poll(async () => (await session.readSavedVault()).students.length).toBe(15);
  saved = await session.readSavedVault();
  expect(saved.students.find(student => student.name === "无年级新生")?.grade).toBeUndefined();
  expect(saved.students.filter(student => vault.students.some(original => original.id === student.id))).toEqual(vault.students);
  expect(saved.courseGroups).toEqual(vault.courseGroups);
  expect(saved.lessons).toEqual(vault.lessons);
  expect(session.pageErrors).toEqual([]);
  expect(session.unexpectedRequests).toEqual([]);
});

test("student filters preserve combined scopes, tab state and deleted course-type reset", async ({ page, context }) => {
  const vault = createBenchmarkVault({ students: 12, courses: 1, lessons: 3 });
  vault.profile.homeCampusId = "campus_a";
  vault.students[0] = { ...vault.students[0], grade: undefined };
  vault.students[1] = { ...vault.students[1], grade: "初二", temporaryTrial: true, note: "筛选备注" };
  vault.students[2] = { ...vault.students[2], status: "transition" };
  const session = await openSyntheticWorkspace(page, context, vault);
  await page.getByRole("button", { name: "档案信息", exact: true }).click();
  await page.getByRole("button", { name: "学生列表", exact: true }).click();
  await listFilter(page, "全部学生").selectOption("transition");
  await expect(studentRows(page)).toHaveCount(1);
  await expect(page.getByRole("checkbox", { name: "选择学生 合成学生0002", exact: true })).toBeVisible();
  await listFilter(page, "全部学生").selectOption("archived");
  await expect(page.getByRole("checkbox", { name: "选择学生 合成学生0010", exact: true })).toBeVisible();
  await listFilter(page, "全部学生").selectOption("active");
  await listFilter(page, "全部年级").selectOption("__unset");
  await expect(studentRows(page)).toHaveCount(1);
  await expect(page.getByRole("checkbox", { name: "选择学生 合成学生0000", exact: true })).toBeVisible();
  await listFilter(page, "全部年级").selectOption("初二");
  await listFilter(page, "全部档案").selectOption("trial");
  await listFilter(page, "全部校区").selectOption("campus_b");
  await listFilter(page, "全部班型").selectOption("small_class");
  await listFilter(page, "全部科目").selectOption("语文");
  await page.getByPlaceholder("搜索学生姓名、学校或备注").fill("  筛选备注  ");
  await expect(studentRows(page)).toHaveCount(1);
  await expect(page.getByRole("checkbox", { name: "选择学生 合成学生0001", exact: true })).toBeVisible();
  await page.getByRole("button", { name: "添加课程档案", exact: true }).click();
  await page.getByRole("button", { name: "学生列表", exact: true }).click();
  await expect(listFilter(page, "全部年级")).toHaveValue("初二");
  await expect(listFilter(page, "全部档案")).toHaveValue("trial");
  await expect(studentRows(page)).toHaveCount(1);
  await listFilter(page, "全部班型").selectOption("one_on_one");
  await expect(studentRows(page)).toHaveCount(0);
  await page.getByRole("button", { name: "校区与班型", exact: true }).click();
  const typeCard = page.locator('div[class~="space-y-3"][class~="p-3"]').filter({ has: page.locator("span").getByText("一对一", { exact: true }) });
  await typeCard.getByRole("button", { name: "删除", exact: true }).click();
  await page.getByRole("dialog", { name: "删除班型「一对一」？", exact: true }).getByRole("button", { name: "删除", exact: true }).click();
  await expect.poll(async () => (await session.readSavedVault()).preferences?.disabledCourseTypes ?? []).toContain("one_on_one");
  await page.getByRole("button", { name: "学生列表", exact: true }).click();
  await expect(listFilter(page, "全部班型")).toHaveValue("all");
  await expect(listFilter(page, "全部班型").locator('option[value="one_on_one"]')).toHaveCount(0);
  await expect(studentRows(page)).toHaveCount(1);
  const saved = await session.readSavedVault();
  expect(saved.students).toEqual(vault.students);
  expect(saved.courseGroups).toEqual(vault.courseGroups);
  expect(saved.lessons).toEqual(vault.lessons);
  expect(session.pageErrors).toEqual([]);
  expect(session.unexpectedRequests).toEqual([]);
});
